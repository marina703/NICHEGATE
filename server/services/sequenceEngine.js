// SEQUENCES ENGINE — Kit-lite email launch sequences (Phase 5).
// NicheGate is the brain: it generates per-niche sequences (welcome / launch /
// follow-up), keeps them in sync with live trend + seasonal data, and exports
// to an ESP. HARD RULE: NicheGate never sends email itself — deliverability
// is the ESP's product (Kit V4 or MailerLite; subscriber sync is theirs too).
// AI optional: deterministic fallbacks honor MODEL_ENABLED=false.
// ═══════════════════════════════════════════════════════════════════════════

const { db } = require('../database');

// Email export payloads go ONLY to the configured ESP webhook — the owner's
// automation (Zapier/Make/native ESP hook) performs the actual import.
function espWebhook() {
  const { isRealSecret } = require('./credentialGuard');
  try {
    const row = db.prepare("SELECT value FROM settings WHERE key = 'esp_webhook_url'").get();
    if (row && isRealSecret(row.value)) return String(row.value).trim();
  } catch { /* none set */ }
  return isRealSecret(process.env.ESP_WEBHOOK_URL) ? process.env.ESP_WEBHOOK_URL : null;
}

const STRUCTURES = {
  welcome: [
    { day: 0, role: 'deliver', note: 'Deliver the lead magnet + set expectations' },
    { day: 1, role: 'story', note: 'Your story: why you build for this niche' },
    { day: 3, role: 'value', note: 'One quick win they can use today' },
    { day: 5, role: 'offer', note: 'Introduce the toolkit (soft pitch)' },
    { day: 7, role: 'close', note: 'What buyers say + final invite' }
  ],
  launch: [
    { day: 0, role: 'problem', note: 'Name the painful problem in this niche' },
    { day: 2, role: 'reveal', note: 'Reveal the product as the fix' },
    { day: 4, role: 'proof', note: 'Proof, screenshots, what is inside' },
    { day: 6, role: 'urgency', note: 'Launch pricing ends soon' }
  ],
  followup: [
    { day: 0, role: 'checkin', note: 'How is the template working for you?' },
    { day: 3, role: 'tip', note: 'Advanced tip for the tool they bought' },
    { day: 7, role: 'sibling', note: 'Offer a sibling product from the same niche' }
  ]
};

function deterministicEmails(profName, purpose, products) {
  const role = {
    welcome: ['Deliver + promise', 'Your story', 'Quick win', 'Soft offer', 'Social proof + invite'],
    launch: ['Problem', 'Reveal', 'Proof', 'Urgency'],
    followup: ['Check-in', 'Advanced tip', 'Sibling offer']
  }[purpose] || ['Touch'];
  const pick = products && products.length
    ? products.map(p => `${p.name} (${'$' + String(p.price).replace('$', '') || '12'})`).slice(0, 3).join(', ')
    : 'the Complete Toolkit';
  return role.map((r, i) => ({
    day: STRUCTURES[purpose] ? STRUCTURES[purpose][i].day : i * 2,
    role: r,
    subject: `${profName}: ${r} — ${purpose === 'launch' ? 'new toolkit' : purpose === 'welcome' ? 'your download' : 'quick check-in'}`,
    body: `Hi {{first_name}},\n\n${r} for ${profName}. This email covers: ${pick}.\n\n— sent by your ESP, generated by NicheGate`
  }));
}

async function aiEmail(subject, body, profName) {
  try {
    const ce = require('./conceptEngine');
    const raw = await ce.generateSocialPost(
      `Write a warm, direct email body for: "${subject}". Context: ${body} Audience: ${profName} small business owners. Sign as — sent by your ESP.`,
      profName
    );
    if (raw && raw.length > 40) return String(raw).slice(0, 2000);
  } catch { /* fallback below */ }
  return body;
}

// Generate (or regenerate) a sequence for a niche/trend.
async function generateSequence({ professionId, trendKey, purpose = 'launch' }) {
  let prof = null;
  if (professionId) prof = db.prepare('SELECT * FROM professions WHERE id = ?').get(professionId);
  const profName = prof ? prof.name : (trendKey || 'this niche');
  const products = prof
    ? db.prepare("SELECT name, price FROM products WHERE profession_id = ? AND status IN ('draft','pending-review','listed') ORDER BY id DESC LIMIT 5").all(prof.id)
    : [];

  const structure = STRUCTURES[purpose] || STRUCTURES.launch;
  const det = deterministicEmails(profName, purpose, products);
  const emails = [];
  for (let i = 0; i < structure.length; i++) {
    const s = structure[i];
    const base = det[i] || det[det.length - 1];
    emails.push({
      day: s.day,
      role: s.role,
      note: s.note,
      subject: base.subject,
      body: await aiEmail(base.subject, base.body, profName)
    });
  }

  const name = `${profName} · ${purpose}`;
  // One ready sequence per (prof/trend, purpose): regenerate replaces.
  const existing = db.prepare(
    'SELECT id FROM sequences WHERE profession_id IS ? AND trend_key IS ? AND purpose = ?'
  ).get(professionId || null, trendKey || null, purpose);
  if (existing) {
    db.prepare('UPDATE sequences SET name = ?, emails = ?, status = ?, created_at = CURRENT_TIMESTAMP WHERE id = ?')
      .run(name, JSON.stringify(emails), 'ready', existing.id);
    return { ok: true, id: existing.id, name, emails, regenerated: true };
  }
  const info = db.prepare(
    'INSERT INTO sequences (profession_id, trend_key, name, purpose, emails, status) VALUES (?, ?, ?, ?, ?, ?)'
  ).run(professionId || null, trendKey || null, name, purpose, JSON.stringify(emails), 'ready');
  return { ok: true, id: info.lastInsertRowid, name, emails, regenerated: false };
}

// Export a sequence to the ESP webhook. NicheGate hands off; it never sends.
async function exportSequence(id) {
  const seq = db.prepare('SELECT * FROM sequences WHERE id = ?').get(id);
  if (!seq) throw new Error('Sequence not found');
  const hook = espWebhook();
  if (!hook) {
    return { ok: false, reason: 'No ESP webhook configured (set esp_webhook_url in settings or ESP_WEBHOOK_URL env) — emails are ready to copy below', emails: JSON.parse(seq.emails || '[]') };
  }
  const axios = require('axios');
  const resp = await axios.post(hook, {
    event: 'nichegate.sequence.export',
    sequence: { id: seq.id, name: seq.name, purpose: seq.purpose },
    emails: JSON.parse(seq.emails || '[]')
  }, { timeout: 15000 });
  db.prepare("UPDATE sequences SET status = 'exported' WHERE id = ?").run(id);
  return { ok: true, webhook: true, status: resp.status };
}

function listSequences(limit = 50) {
  return db.prepare('SELECT id, profession_id, trend_key, name, purpose, status, created_at FROM sequences ORDER BY id DESC LIMIT ?').all(limit);
}

function getSequence(id) {
  const seq = db.prepare('SELECT * FROM sequences WHERE id = ?').get(id);
  if (!seq) return null;
  return { ...seq, emails: JSON.parse(seq.emails || '[]') };
}

module.exports = { generateSequence, exportSequence, listSequences, getSequence, STRUCTURES, deterministicEmails, espWebhook };
